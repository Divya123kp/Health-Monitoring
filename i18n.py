def tr(key, lang=DEFAULT_LANG, **kw):
    entry = S.get(key)
    if entry is None:
        return key
    text = entry.get(lang) or entry.get(DEFAULT_LANG) or key
    if kw:
        try:
            text = text.format(**kw)
        except (KeyError, IndexError):
            pass
    return text


def normalize_lang(lang):
    return lang if lang in LANGS else DEFAULT_LANG


def js_bundle(lang):
    """Flat {key: text} for window.I18N (browser side)."""
    lang = normalize_lang(lang)
    return {k: (v.get(lang) or v[DEFAULT_LANG]) for k, v in S.items()}
